const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const resultFile=path.join(root,'work','desktop-smoke-result.json');
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
exports.run=async function({window,app,store}){
  const report={startedAt:new Date().toISOString(),checks:[],catalogue:null,console:[]};
  fs.mkdirSync(path.dirname(resultFile),{recursive:true});
  const run=(code,userGesture=true)=>window.webContents.executeJavaScript(code,userGesture);
  const until=async (code,timeout=10000)=>{const end=Date.now()+timeout;while(Date.now()<end){if(await run(code))return;await wait(100);}throw new Error('Timed out: '+code);};
  const click=selector=>run(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const native=()=>run('window.velvet.readState()');
  const check=(name)=>{report.checks.push(name);fs.writeFileSync(resultFile,JSON.stringify(report,null,2));console.log('PASS',name);};
  const input=(selector,value)=>run(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw new Error('Missing input: '+${JSON.stringify(selector)});if(e.type==='checkbox')e.checked=${JSON.stringify(value)};else e.value=${JSON.stringify(String(value))};e.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  const persistAndReload=async settings=>{
    await run(`import(new URL('./app.js',location.href).href).then(m=>m.applySetup(${JSON.stringify(settings)}))`);
    await until(`window.velvet.readState().then(s=>s.settings.background?.id===${JSON.stringify(settings.background.id)})`);
    await store.pending;
    await new Promise(resolve=>{window.webContents.once('did-finish-load',resolve);window.webContents.reload();});
    await until("document.body.dataset.ready==='true'");
  };
  window.webContents.setBackgroundThrottling(false);
  const consoleListener=(...args)=>{const details=args[1];const message=typeof details==='object'?details.message:args[2];report.console.push(String(message||'').slice(0,1800));report.console=report.console.slice(-30);};
  window.webContents.on('console-message',consoleListener);
  fs.writeFileSync(resultFile,JSON.stringify(report,null,2));
  try{
    await until("document.body.dataset.ready==='true'");
    await wait(500);
    assert.match(await run("document.querySelector('#content').textContent"),/Find your frequency/);
    assert.ok(await run("document.querySelectorAll('#navigation button').length>=6"));
    check('Renderer modules load and navigation is populated');
    const initial=await native();
    assert.ok(initial.tracks.filter(t=>t.source==='local').length>=3);
    const demo=initial.tracks.find(t=>t.source==='local');
    const range=await run(`fetch(${JSON.stringify(demo.mediaUrl)},{headers:{Range:'bytes=0-43'}}).then(async r=>({status:r.status,bytes:(await r.arrayBuffer()).byteLength}))`);
    assert.equal(range.status,206);assert.equal(range.bytes,44);
    check('Local media protocol streams exact byte ranges');
    const output=path.join(root,'work','screenshots');fs.mkdirSync(output,{recursive:true});
    fs.writeFileSync(path.join(output,'Velvet-preview.png'),(await window.webContents.capturePage()).toPNG());
    // Restored queue playback must initialize the same real DSP pipeline.
    await click('#play-main');
    await until("!document.querySelector('#audio').paused&&document.querySelector('#audio').currentTime>.15");
    assert.equal(await run("document.querySelector('#audio').error"),null);
    await click('[data-action="navigate"][data-route="lab"]');
    report.rendererVisibility=await run('document.visibilityState');
    if(await run('!document.hidden')){
      await until("document.querySelector('#lab-analysis-status')?.textContent.includes('Live spectrum')&&Number.parseFloat(document.querySelector('#lab-level-label')?.textContent)>-100");
      check('First Play on a restored queue initializes DSP and produces a real nonzero output meter');
    }else{
      assert.match(await run("document.querySelector('#lab-analysis-status').textContent"),/Local audio analysis/i);
      check('First Play on a restored queue initializes DSP; hidden-window visualisation stays suspended');
    }
    await input('[data-audio="gain"]',150);
    await until('window.velvet.readState().then(s=>s.settings.audio.gain===1.5)');
    await click('[data-action="audio-preset"][data-preset="Bass Boost"]');
    await until('window.velvet.readState().then(s=>s.settings.audio.tones.bass===5)');
    await click('[data-action="audio-bypass"]');
    await until('window.velvet.readState().then(s=>s.settings.audio.bypass===true)');
    await click('[data-action="audio-reset"]');
    await until('window.velvet.readState().then(s=>s.settings.audio.gain===1&&s.settings.audio.limiter===true&&s.settings.audio.bypass===false)');
    check('Audio Lab gain, presets, A/B bypass and reset persist through real interface controls');
    await click('[data-action="navigate"][data-route="discover"]');
    await click('[data-action="play-mix"]');
    await until("!document.querySelector('#audio').paused&&document.querySelector('#audio').currentTime>.15");
    check('Bundled original audio starts and its playback clock advances');
    await click(`[data-action="track-menu"][data-id="${demo.id}"]`);
    await click(`[data-action="play-next"][data-id="${demo.id}"]`);
    await click('[data-action="next"]');await wait(600);
    assert.equal((await native()).queueIndex,1);
    check('Repeated queue entries advance to the intended occurrence');
    await click('[data-action="navigate"][data-route="lab"]');
    assert.match(await run("document.querySelector('#content').textContent"),/Audio Lab|Audio lab|sound/i);
    const sliders=await run("Array.from(document.querySelectorAll('[data-audio]')).map(e=>({id:e.id,key:e.dataset.audio,tone:e.dataset.key}))");
    assert.ok(sliders.length>20);
    check('Audio Lab exposes the real effect controls');
    report.audio=await require('./audio-offline.cjs').run(window);
    check('Actual offline audio verifies gain, EQ, tones, mono, reverb, compression, limiter and smooth changes');
    fs.writeFileSync(path.join(output,'Velvet-audio-lab.png'),(await window.webContents.capturePage()).toPNG());
    await click('[data-action="navigate"][data-route="appearance"]');
    await click('[data-action="theme"][data-value="dusk"]');
    await run("(()=>{const e=document.querySelector('[data-setting=radius]');e.value=22;e.dispatchEvent(new Event('input',{bubbles:true}));})()");
    await wait(600);
    assert.equal((await native()).settings.radius,22);
    assert.equal((await native()).settings.theme,'dusk');
    check('Theme and layout controls persist their real settings');
    // Seed background fixtures through the privileged test harness, then exercise the real media protocol and renderer.
    const backgrounds=path.join(app.getPath('userData'),'backgrounds');fs.mkdirSync(backgrounds,{recursive:true});
    const imageName='11111111-1111-4111-8111-111111111111.png';
    fs.copyFileSync(path.join(root,'assets','icon.png'),path.join(backgrounds,imageName));
    let persisted=await native();persisted.settings.background={id:imageName,name:'Test wallpaper.png',type:'image',url:'velvet-media://background/'+imageName};
    await persistAndReload(persisted.settings);
    await until("document.querySelector('#background img')?.naturalWidth>0");
    check('Image wallpaper loads through a persisted local background reference');
    const gifName='22222222-2222-4222-8222-222222222222.gif';
    fs.writeFileSync(path.join(backgrounds,gifName),Buffer.from('R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7','base64'));
    persisted=await native();persisted.settings.background={id:gifName,name:'Test animation.gif',type:'image',url:'velvet-media://background/'+gifName};
    await persistAndReload(persisted.settings);await until("document.querySelector('#background img')?.naturalWidth>0");
    check('GIF wallpapers load after restarting the renderer');
    const videoBytes=await run(`new Promise(async(resolve,reject)=>{try{const canvas=document.createElement('canvas');canvas.width=80;canvas.height=80;const ctx=canvas.getContext('2d');ctx.fillStyle='#d4b7ff';ctx.fillRect(0,0,80,80);const stream=canvas.captureStream(5);const rec=new MediaRecorder(stream,{mimeType:'video/webm'});const chunks=[];rec.ondataavailable=e=>chunks.push(e.data);rec.onstop=async()=>{stream.getTracks().forEach(t=>t.stop());resolve(Array.from(new Uint8Array(await new Blob(chunks,{type:'video/webm'}).arrayBuffer())));};rec.onerror=reject;rec.start();setTimeout(()=>{ctx.fillStyle='#507466';ctx.fillRect(0,0,80,80);},200);setTimeout(()=>rec.stop(),600);}catch(e){reject(e);}})`);
    const videoName='33333333-3333-4333-8333-333333333333.webm';fs.writeFileSync(path.join(backgrounds,videoName),Buffer.from(videoBytes));
    persisted=await native();persisted.settings.background={id:videoName,name:'Test loop.webm',type:'video',url:'velvet-media://background/'+videoName};
    await persistAndReload(persisted.settings);await until("document.querySelector('#background video')?.readyState>=2");
    assert.equal(await run("document.querySelector('#background video').muted"),true);
    assert.equal(await run("document.querySelector('#background video').loop"),true);
    check('Video wallpaper is playable, muted, looping and restored');
    await click('[data-action="new-playlist"]');
    await run("document.querySelector('#playlist-name').value='Smoke test collection'");await click('#create-playlist-button');await wait(600);
    assert.ok((await native()).playlists.some(p=>p.name==='Smoke test collection'));
    check('Playlists are created and persisted through the interface');
    await click('[data-action="navigate"][data-route="discover"]');
    const favButton=`[data-action="favorite"][data-id="${demo.id}"]`;await click(favButton);await wait(600);
    assert.ok((await native()).favorites.includes(demo.id));check('Favourites persist from the interface');
    await run("document.querySelector('#global-search').value='Daft Punk';document.querySelector('#search-form').requestSubmit()");
    await until("!document.querySelector('#content').textContent.includes('Searching…')",18000);
    const searchText=await run("document.querySelector('#content').textContent");
    assert.ok(/Audius|unavailable|No playable songs/.test(searchText));
    report.catalogue=searchText.includes('playable songs from Audius')?'Live playable catalogue query succeeded':searchText.match(/Catalogue search is unavailable:[\s\S]*?(?:above\.)/)?.[0]||'No live catalogue match';
    check('Song search resolves live results or gives a clear provider fallback');
    await run("document.querySelector('#global-search').value='Electronic Butterflies';document.querySelector('#search-form').requestSubmit()");
    await until("document.querySelector('[data-track-row=\"audius:abkvg\"]')!==null",25000);
    fs.writeFileSync(path.join(output,'Velvet-song-search.png'),(await window.webContents.capturePage()).toPNG());
    await click('[data-action="play-track"][data-id="audius:abkvg"]');
    await until("document.querySelector('#audio').currentSrc.includes('velvet-media://stream/abkvg')&&!document.querySelector('#audio').paused&&document.querySelector('#audio').currentTime>.5",30000);
    const streamed=await run("({duration:document.querySelector('#audio').duration,url:location.href,error:document.querySelector('#audio').error})");
    assert.ok(streamed.duration>110&&streamed.duration<130,'full song duration, not a short preview');assert.equal(streamed.error,null);assert.match(streamed.url,/index.html/);
    check('Live song search starts a full-length Audius track inside Velvet without navigating away');
    await run("document.querySelector('#audio').currentTime=20");await until("document.querySelector('#audio').currentTime>20",15000);
    await click('[data-action="navigate"][data-route="lab"]');
    if(await run('!document.hidden'))await until("Number.parseFloat(document.querySelector('#lab-level-label')?.textContent)>-100",15000);
    check('Streamed songs support real seeking and the existing audio engine');
    await click('#play-main');await wait(600);assert.equal(await run("document.querySelector('#audio').paused"),true);
    const streamState=await native();assert.ok(streamState.tracks.some(t=>t.id==='audius:abkvg'));assert.ok(streamState.queue.includes('audius:abkvg'));
    check('Streaming playback pauses and its song and queue reference persist');
    const final=await native();assert.equal(final.settings.theme,'dusk');assert.equal(final.settings.radius,22);
    check('Queue, playlists, favourites, background and theme survive renderer reloads');
    await store.pending;report.ok=true;report.completedAt=new Date().toISOString();fs.writeFileSync(resultFile,JSON.stringify(report,null,2));console.log('DESKTOP_SMOKE_OK',JSON.stringify(report));
  }catch(error){report.ok=false;report.error=error.stack||error.message;if(error.metrics)report.audio=error.metrics;try{report.rendererText=await run("document.body.textContent.slice(0,7000)");}catch{}fs.writeFileSync(resultFile,JSON.stringify(report,null,2));try{fs.writeFileSync(path.join(root,'work','desktop-failure.png'),(await window.webContents.capturePage()).toPNG());}catch{}throw error;}finally{window.webContents.removeListener('console-message',consoleListener);}
};
